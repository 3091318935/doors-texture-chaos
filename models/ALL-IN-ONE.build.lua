local Workspace = game:GetService("Workspace")

-- Selection / ChangeHistoryService 只在 Studio 里有；执行器里 getService 会直接报错，
-- 所以必须包 pcall，否则整个脚本第一行就死了
local Selection = nil
pcall(function()
	Selection = game:GetService("Selection")
end)
local ChangeHistoryService = nil
pcall(function()
	ChangeHistoryService = game:GetService("ChangeHistoryService")
end)

local recording
pcall(function()
	recording = ChangeHistoryService:TryBeginRecording("Build Figure rig")
end)

local folder = Workspace:FindFirstChild(CONFIG.folderName)
if not folder then
	folder = Instance.new("Folder")
	folder.Name = CONFIG.folderName
	folder.Parent = Workspace
end

local old = folder:FindFirstChild(CONFIG.modelName)
if old then
	old:Destroy()
end

local model = Instance.new("Model")
model.Name = CONFIG.modelName

local built = 0
local skipped = 0

for _, row in ipairs(PARTS) do
	local name, meshId = row[1], row[2]
	local worldPos = Vector3.new(row[3], row[4], row[5])
	local size = Vector3.new(row[15], row[16], row[17])

	if not meshId then
		skipped = skipped + 1
		continue
	end

	local part = Instance.new("MeshPart")
	part.Name = name
	part.MeshId = "rbxassetid://" .. meshId
	part.Size = size
	part.Anchored = CONFIG.anchored
	part.CanCollide = false
	part.CanTouch = false
	part.CastShadow = CONFIG.castShadow
	part.Massless = true

	local offset = worldPos - PIVOT + CONFIG.placeAt
	part.CFrame = CFrame.new(offset)
		* CFrame.new(0, 0, 0,
			row[6], row[7], row[8],
			row[9], row[10], row[11],
			row[12], row[13], row[14])

	part.Parent = model
	built = built + 1
end

model.Parent = folder

if recording then
	pcall(function()
		ChangeHistoryService:FinishRecording(recording, Enum.FinishRecordingOperation.Commit)
	end)
end

pcall(function() Selection:Set({ model }) end)

print(string.format("[FigureRig] 重建 %d 个 MeshPart（跳过 %d 个无网格部件）-> %s", built, skipped, model:GetFullName()))
