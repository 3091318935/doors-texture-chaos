local function buildRig(def, folder, placeAt)
	-- 重心：只算有 CFrame 的部件；没有 CFrame 的部件放到重心上
	local sum, count = Vector3.zero, 0
	for _, row in ipairs(def.parts) do
		if row[3] ~= nil then
			sum = sum + Vector3.new(row[3], row[4], row[5])
			count = count + 1
		end
	end
	local pivot = if count > 0 then sum / count else Vector3.zero

	local old = folder:FindFirstChild(def.name)
	if old then
		old:Destroy()
	end

	local model = Instance.new("Model")
	model.Name = def.name

	local byName = {}
	local built = 0

	for _, row in ipairs(def.parts) do
		local part = Instance.new("MeshPart")
		part.Name = row[1]
		part.MeshId = "rbxassetid://" .. row[2]
		part.Size = Vector3.new(row[15], row[16], row[17])
		part.Anchored = CONFIG.anchored
		part.CanCollide = false
		part.CanTouch = false
		part.CastShadow = CONFIG.castShadow
		part.Massless = true

		if row[3] ~= nil then
			local offset = Vector3.new(row[3], row[4], row[5]) - pivot + placeAt
			part.CFrame = CFrame.new(offset)
				* CFrame.new(0, 0, 0,
					row[6], row[7], row[8],
					row[9], row[10], row[11],
					row[12], row[13], row[14])
		else
			part.CFrame = CFrame.new(placeAt)
		end

		part.Parent = model
		byName[part.Name] = part
		built = built + 1
	end

	-- 贴图挂到指定部件上（正脸）
	local decalList = def.decals or (if def.decal then { def.decal } else {})
	for _, entry in ipairs(decalList) do
		if entry.texture then
			local host = byName[entry.part] or model:FindFirstChildWhichIsA("MeshPart")
			if host then
				local decal = Instance.new("Decal")
				decal.Name = def.name .. "Face"
				decal.Face = Enum.NormalId.Front
				decal.Texture = entry.texture
				decal.Parent = host
			end
		end
	end

	model.Parent = folder
	return model, built
end

