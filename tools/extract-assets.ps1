#Requires -Version 5.1
<#
  extract-assets.ps1 v3  (ASCII only - safe for PowerShell 5.1)

  v3 fixes: part properties are no longer read from a fixed 1500-char window.
  Each MeshPart / Decal slice is bounded by the next <Item tag, and every
  property regex now tolerates both CDATA and plain-text serialization.

  Finds CHARACTER models (a Model containing a Humanoid) and lists:
      part  <name>  mesh=rbxassetid://...  tex=rbxassetid://...
      decal <name>  tex=rbxassetid://...

  Usage:
      powershell -ExecutionPolicy Bypass -File tools\extract-assets.ps1
      powershell -ExecutionPolicy Bypass -File tools\extract-assets.ps1 -DumpParts
#>
[CmdletBinding()]
param(
    [string]$Path = 'D:\DSH ROBLOX\doors_downloads',
    [string]$Out = '',
    [switch]$DumpParts
)

$ErrorActionPreference = 'Continue'

if ([string]::IsNullOrWhiteSpace($Out)) {
    $Out = Join-Path (Split-Path -Parent $PSScriptRoot) 'assets.lua'
}

if (-not (Test-Path -LiteralPath $Path)) {
    Write-Host "dir not found: $Path" -ForegroundColor Red
    exit 1
}

$files = @(Get-ChildItem -LiteralPath $Path -Recurse -File -Include *.rbxlx, *.rbxmx -ErrorAction SilentlyContinue)
if ($files.Count -eq 0) { Write-Host 'no xml files' -ForegroundColor Yellow; exit 1 }

Write-Host ("scanning {0} xml file(s)..." -f $files.Count) -ForegroundColor Cyan

$modelTag = [regex]'<Item class="Model"\s+referent="[^"]*">'
$itemTag = [regex]'<Item class="'
$nameRegex = New-Object System.Text.RegularExpressions.Regex('<string name="Name">(?:<!\[CDATA\[)?(.*?)(?:\]\]>)?</string>', [System.Text.RegularExpressions.RegexOptions]::Singleline)
$meshRegex = [regex]'<Content name="MeshId"><url>(?:<!\[CDATA\[)?(?:rbxassetid://)?(\d+)'
$texIdRegex = [regex]'<Content name="TextureID"><url>(?:<!\[CDATA\[)?(?:rbxassetid://)?(\d+)'
$texRegex = [regex]'<Content name="Texture"><url>(?:<!\[CDATA\[)?(?:rbxassetid://)?(\d+)'
$itemClassRegex = [regex]'<Item class="(MeshPart|Decal|Texture)"'

$report = New-Object System.Collections.Generic.List[string]
$lua = New-Object System.Collections.Generic.List[string]
$charTotal = 0
$modelTotal = 0
$bad = @()

$lua.Add('-- generated by tools/extract-assets.ps1 v3')
$lua.Add(('-- {0}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')))
$lua.Add('return {')

function Take-ItemSlice($text, $index, $max) {
    # slice from index up to the next <Item tag, capped at $max chars
    $limit = [math]::Min($index + $max, $text.Length)
    $rest = $text.Substring($index, $limit - $index)
    $m = $itemTag.Match($rest, 1)
    if ($m.Success) { return $rest.Substring(0, $m.Index) }
    return $rest
}

function Get-Prop($regex, $slice) {
    $m = $regex.Match($slice)
    if ($m.Success) { return $m.Groups[1].Value }
    return ''
}

foreach ($file in $files) {
    $sizeMb = [math]::Round($file.Length / 1MB, 1)
    $report.Add('')
    $report.Add(('=' * 72))
    $report.Add(('FILE: {0}   ({1} MB)' -f $file.Name, $sizeMb))
    $report.Add(('=' * 72))

    $text = $null
    try { $text = Get-Content -LiteralPath $file.FullName -Raw -Encoding UTF8 -ErrorAction Stop }
    catch {
        $report.Add("  READ FAILED: $($_.Exception.Message)")
        $bad += $file.Name
        continue
    }
    if (-not $text) { continue }

    if (-not $text.TrimEnd().EndsWith('</roblox>')) {
        $report.Add('  INCOMPLETE FILE: truncated download')
        $bad += $file.Name
    }

    $models = $modelTag.Matches($text)
    $fileModels = 0
    $fileChars = 0
    $seen = @{}

    for ($i = 0; $i -lt $models.Count; $i++) {
        $start = $models[$i].Index
        $end = if ($i + 1 -lt $models.Count) { $models[$i + 1].Index } else { $text.Length }
        if ($end -le $start) { continue }
        $chunk = $text.Substring($start, $end - $start)
        $fileModels++

        if ($chunk.IndexOf('<Item class="Humanoid"') -lt 0) { continue }

        $nameMatch = $nameRegex.Match($chunk)
        $modelName = if ($nameMatch.Success) { $nameMatch.Groups[1].Value } else { '(unnamed)' }

        # walk MeshPart / Decal / Texture in document order so a Decal can be
        # attached to the MeshPart it belongs to (that is the face texture)
        $parts = @()
        $orphanDecals = @()
        $current = $null
        foreach ($hit in $itemClassRegex.Matches($chunk)) {
            $class = $hit.Groups[1].Value
            $slice = Take-ItemSlice $chunk $hit.Index 12000
            $nm = Get-Prop $nameRegex $slice
            if ($class -eq 'MeshPart') {
                $mv = Get-Prop $meshRegex $slice
                $tv = Get-Prop $texRegex $slice
                if ($mv) { $mv = 'rbxassetid://' + $mv }
                if ($tv) { $tv = 'rbxassetid://' + $tv }
                $current = [pscustomobject]@{
                    Name    = $nm
                    Mesh    = $mv
                    Texture = $tv
                    Decals  = @()
                }
                $parts += $current
            }
            else {
                $tex = Get-Prop $texRegex $slice
                if ($tex) { $tex = 'rbxassetid://' + $tex }
                if ($null -ne $current) { $current.Decals += [pscustomobject]@{ Name = $nm; Texture = $tex } }
                else { $orphanDecals += [pscustomobject]@{ Name = $nm; Texture = $tex } }
            }
        }

        $decals = @($orphanDecals)
        foreach ($p in $parts) { foreach ($d in $p.Decals) { $decals += $d } }

        $sig = $modelName + '|' + (($parts | ForEach-Object { "$($_.Name):$($_.Mesh)" }) -join ',')
        if ($seen.ContainsKey($sig)) { continue }
        $seen[$sig] = $true

        $fileChars++
        $charTotal++

        $withMesh = @($parts | Where-Object { $_.Mesh -ne '' }).Count
        $report.Add('')
        $report.Add(('  [CHARACTER] {0}   parts={1} (with mesh {2})  decals={3}' -f $modelName, $parts.Count, $withMesh, $decals.Count))

        if ($DumpParts -or $true) {
            foreach ($p in $parts) {
                $report.Add(('      part  {0,-24} mesh={1,-26} tex={2}' -f $p.Name, $p.Mesh, $p.Texture))
            }
            foreach ($d in $decals) {
                $report.Add(('      decal {0,-24} tex={1}' -f $d.Name, $d.Texture))
            }
        }

        $safe = $modelName -replace '\\', '\\' -replace '"', '\"'
        $lua.Add(('    {{ file = "{0}", name = "{1}",' -f ($file.Name -replace '"', '\"'), $safe))
        $lua.Add('      parts = {')
        foreach ($p in $parts) {
            $lua.Add(('        {{ name = "{0}", mesh = "{1}", texture = "{2}" }},' -f ($p.Name -replace '"', '\"'), $p.Mesh, $p.Texture))
        }
        $lua.Add('      },')
        $lua.Add('      decals = {')
        foreach ($d in $decals) {
            $lua.Add(('        {{ name = "{0}", texture = "{1}" }},' -f ($d.Name -replace '"', '\"'), $d.Texture))
        }
        $lua.Add('      } },')
    }

    $modelTotal += $fileModels
    $report.Add('')
    $report.Add(("  -> {0} model block(s), {1} character rig(s)" -f $fileModels, $fileChars))
}

$lua.Add('}')

$reportPath = Join-Path (Split-Path -Parent $Out) 'assets-report.txt'
Set-Content -LiteralPath $reportPath -Value ($report -join "`r`n") -Encoding UTF8
Set-Content -LiteralPath $Out -Value ($lua -join "`r`n") -Encoding UTF8

Write-Host ''
Write-Host ("done: {0} model block(s), {1} character rig(s)" -f $modelTotal, $charTotal) -ForegroundColor Green
if ($bad.Count -gt 0) { Write-Host ("incomplete/locked: {0}" -f ($bad -join ', ')) -ForegroundColor Yellow }
Write-Host ("report: {0}" -f $reportPath) -ForegroundColor Cyan
Write-Host ("lua   : {0}" -f $Out) -ForegroundColor Cyan
